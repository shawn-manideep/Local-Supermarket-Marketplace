export type InitialMasterCategoryName = (typeof INITIAL_MASTER_CATEGORY_NAMES)[number];

export type InitialMasterProduct = {
  categoryName: InitialMasterCategoryName;
  name: string;
  description: string;
  image: null;
  brand: string | null;
  attributes: Record<string, string>;
};

type ProductEntry = readonly [name: string, description: string, brand?: string];

function product(
  categoryName: InitialMasterCategoryName,
  [name, description, brand]: ProductEntry,
): InitialMasterProduct {
  return {
    categoryName,
    name,
    description,
    image: null,
    brand: brand ?? null,
    attributes: {},
  };
}

function products(
  categoryName: InitialMasterCategoryName,
  entries: readonly ProductEntry[],
): InitialMasterProduct[] {
  return entries.map((entry) => product(categoryName, entry));
}

